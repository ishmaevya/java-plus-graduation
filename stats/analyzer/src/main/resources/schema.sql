CREATE TABLE IF NOT EXISTS user_interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    weight DOUBLE PRECISION NOT NULL,
    event_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    viewed BOOLEAN NOT NULL,
    CONSTRAINT uq_user_interactions_user_event UNIQUE (user_id, event_id)
);

CREATE TABLE IF NOT EXISTS event_similarities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_a BIGINT NOT NULL,
    event_b BIGINT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    similarity_timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_event_similarities_events UNIQUE (event_a, event_b)
);
