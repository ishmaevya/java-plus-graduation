CREATE TABLE IF NOT EXISTS subscriptions
(
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id     BIGINT      NOT NULL,
    followed_id     BIGINT      NOT NULL,
    status          VARCHAR(50) NOT NULL,
    created         TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uq_subscription_pair UNIQUE (follower_id, followed_id),
    CONSTRAINT chk_subscription_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELED'))
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_follower ON subscriptions (follower_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_followed ON subscriptions (followed_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status ON subscriptions (status);
